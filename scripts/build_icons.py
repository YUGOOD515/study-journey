"""Build public/static/icons.svg (Lucide sprite) from lucide-static.

Usage:
    npm i --no-save lucide-static
    uv run python scripts/build_icons.py node_modules/lucide-static/icons

Only the icons listed in ICONS go into the sprite. Templates use them via
components/ui.html: {{ icon('search') }}. Stroke width is set in CSS (.icon).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ICONS = """
search x plus check circle-check circle-dashed triangle-alert circle-minus
chevron-left chevron-right chevron-down chevron-up calendar-range arrow-right
lock undo-2 trash-2 wand-sparkles eraser users user-round map-pin clock layers
graduation-cap rotate-ccw refresh-cw info locate-fixed calendar-plus list-checks
pencil history sliders-horizontal grip-vertical
""".split()

OUT = Path(__file__).resolve().parents[1] / "public" / "static" / "icons.svg"


def main(src: str) -> None:
    folder = Path(src)
    version = ""
    symbols = []
    for name in ICONS:
        text = (folder / f"{name}.svg").read_text(encoding="utf-8")
        version = version or (re.search(r"lucide-static v([\d.]+)", text) or [None, ""])[1]
        body = re.search(r"<svg[^>]*>(.*)</svg>", text, re.S)[1]
        body = " ".join(line.strip() for line in body.strip().splitlines())
        symbols.append(f'<symbol id="{name}" viewBox="0 0 24 24">{body}</symbol>')
    OUT.write_text(
        f"<!-- Lucide v{version} (ISC License, https://lucide.dev). Generated by scripts/build_icons.py -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols) + "\n</svg>\n",
        encoding="utf-8",
    )
    print(f"{len(symbols)} icons -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "node_modules/lucide-static/icons")
